    private const int MaxCharactersPerPage = 72;

    public static MysteryStoryDefinition GetStory(int eventId)
    {
        switch (eventId)
        {
            case 1: return Parse(RepeatDayScript);
            case 2: return Parse(CatStoryScript);
            case 3: return Parse(ArtistStoryScript);
            default: return Parse(RepeatDayScript);
        }
    }

    private static MysteryStoryDefinition Parse(string script)
    {
        string title = "特殊事件";
        List<MysteryStoryLine> lines = new List<MysteryStoryLine>();
        string[] rows = script.Replace("\r", string.Empty).Split('\n');
        for (int i = 0; i < rows.Length; i++)
        {
            string row = rows[i].Trim();
            if (string.IsNullOrEmpty(row)) continue;
            if (row.StartsWith("@title|", StringComparison.Ordinal))
            {
                title = row.Substring(7).Trim();
                continue;
            }

            string[] columns = row.Split(new[] { '|' }, 3);
            if (columns.Length < 2) continue;
            string speaker = columns[0].Trim();
            string text = columns[1].Trim();
            string choiceId = columns.Length >= 3 ? columns[2].Trim() : string.Empty;
            AddWrappedLines(lines, speaker, text, choiceId);
        }
        return new MysteryStoryDefinition(title, lines);
    }

    private static void AddWrappedLines(
        List<MysteryStoryLine> destination,
        string speaker,
        string text,
        string choiceId)
    {
        if (string.IsNullOrEmpty(text))
        {
            destination.Add(new MysteryStoryLine(speaker, string.Empty, choiceId));
            return;
        }

        List<string> pages = SplitLongText(text);
        for (int i = 0; i < pages.Count; i++)
        {
            destination.Add(new MysteryStoryLine(
                speaker,
                pages[i],
                i == pages.Count - 1 ? choiceId : string.Empty));
        }
    }

    private static List<string> SplitLongText(string text)
    {
        List<string> pages = new List<string>();
        string remaining = text.Trim();
        while (remaining.Length > MaxCharactersPerPage)
        {
            int breakIndex = FindBreakIndex(remaining);
            pages.Add(remaining.Substring(0, breakIndex).Trim());
            remaining = remaining.Substring(breakIndex).Trim();
        }
        if (remaining.Length > 0) pages.Add(remaining);
        return pages;
    }

    private static int FindBreakIndex(string text)
    {
        int preferred = Math.Min(MaxCharactersPerPage, text.Length - 1);
        for (int i = preferred; i >= MaxCharactersPerPage / 2; i--)
        {
            if (IsSentenceBreak(text[i - 1])) return i;
        }
        for (int i = preferred + 1; i < Math.Min(text.Length, MaxCharactersPerPage + 16); i++)
        {
            if (IsSentenceBreak(text[i - 1])) return i;
        }
        return preferred;
    }

    private static bool IsSentenceBreak(char value)
    {
        return value == '。' || value == '！' || value == '？' || value == '…' ||
               value == '】' || value == '；' || value == '，';
    }

