public sealed class MysteryStoryLine
{
    public string Speaker { get; private set; }
    public string Text { get; private set; }
    public string ChoiceId { get; private set; }

    public MysteryStoryLine(string speaker, string text, string choiceId)
    {
        Speaker = speaker;
        Text = text;
        ChoiceId = choiceId;
    }
}

public sealed class MysteryStoryDefinition
{
    public string Title { get; private set; }
    public List<MysteryStoryLine> Lines { get; private set; }

    public MysteryStoryDefinition(string title, List<MysteryStoryLine> lines)
    {
        Title = title;
        Lines = lines;
    }
}

